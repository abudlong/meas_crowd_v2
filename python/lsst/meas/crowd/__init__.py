"""Adaptive, iterative joint PSF photometry in crowded fields, starting from Gaia positions.

Typical use (a notebook, with the Rubin stack set up)::

    import lsst.meas.crowd as crowd

    cfg = crowd.makeConfig(crowd.CROWDED_FIELD_CONFIG)
    sess = crowd.prepareSession(visit=..., detector=..., cutouts=["1000,1000,300"],
                                 pad=20, psfSource="visit")
    crowd.attachGaia(sess)
    runs = crowd.runSessionGaia(sess, cfg, outDir="results")
    run = runs[next(iter(runs))]
    crowd.plotFinalComparison(run)          # data | model | residual | residual/sigma
    crowd.plotSourceCutouts(run)            # per-source cutouts, cross-sections, magnitudes
    tbl = crowd.measurePhotometry(run)       # astropy Table with PSF / aperture magnitudes

Submodules are imported on first use, so ``import lsst.meas.crowd.fastKernels`` (or the
photometry helpers) works without importing the whole pipeline.
"""

