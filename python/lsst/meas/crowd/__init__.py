def __getattr__(name):
    """Import the defining submodule of a public name on first use (PEP 562)."""
    if name in _WHERE:
        mod = importlib.import_module(f".{_WHERE[name]}", __name__)
        value = getattr(mod, name)
        globals()[name] = value
        return value
    if name in ("pipeline", "gaiaCatalog", "plotting", "photometry", "sourcePlots", "session",
                "fitLib", "adaptive", "fastKernels", "detector", "stagePlots", "runPlots",
                "sparseSolver"):
        return importlib.import_module(f".{name}", __name__)
    if "_" in name.strip("_") and toCamel(name) in _WHERE:   # an old snake_case name
        warnings.warn(f"{name} has been renamed {toCamel(name)}", FutureWarning, stacklevel=2)
        return __getattr__(toCamel(name))
    if name == "gaiaSeeds":                       # the old name of gaiaCatalog
        return importlib.import_module(".gaiaCatalog", __name__)
    if not name.startswith("__"):
        # any other public name of pipeline, plotting or gaiaCatalog
        for modname in ("pipeline", "plotting", "gaiaCatalog"):
            mod = importlib.import_module(f".{modname}", __name__)
            if hasattr(mod, name):
                return getattr(mod, name)
    raise AttributeError(f"module {__name__!r} has no attribute {name!r}")


def __dir__():
    """Return the public names."""
    return __all__
